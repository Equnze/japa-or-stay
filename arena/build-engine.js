// Generates arena/server/engine.generated.js: the single-player game script wrapped in a factory so the server can run
// the exact same rules. Cloudflare Workers forbid eval and new Function, so the game code is pasted into a real function
// body at build time instead. The browser-only parts (screens, sound, storage) run against harmless stubs.
// The factory runs in strict mode on purpose, because Workers load it as an ES module (always strict).
const fs = require('fs');
const path = require('path');

const EXPORTS = ['newState', 'dealHand', 'endWeek', 'choose', 'nextEvent', 'nextWeek', 'startBuild', 'startJapaY2', 'eventView', 'log',
  'CARDS', 'BLOCKS', 'wallet', 'moneyCommitted', 'loanRoom', 'blocksUsed', 'japaProgress', 'REGIONS', 'TRAITS', 'AV_DEFAULT', 'AV_SKINS', 'EV', 'endingInfo'];

function gameScript(html) {
  const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
  if (!scripts.length) throw new Error('No game script found in japa-or-stay.html');
  return scripts[scripts.length - 1];
}

function generateEngine(html) {
  const code = gameScript(html);
  return `// GENERATED by arena/build-engine.js from japa-or-stay.html. Do not edit: run \`node build.js\`.
module.exports = function createEngine() {
  'use strict';
  let __rand = () => { throw new Error('Arena engine used randomness without a seed'); };
  const Math = Object.create(globalThis.Math, { random: { value: () => __rand() } });
  const __el = () => ({ textContent: '', innerHTML: '', value: '', hidden: false, dataset: {}, style: {}, classList: { toggle() {}, add() {}, remove() {}, contains() { return false; } },
    setAttribute() {}, getAttribute() { return null; }, appendChild() {}, querySelector() { return null; }, querySelectorAll() { return []; },
    addEventListener() {}, removeEventListener() {}, focus() {}, scrollIntoView() {}, remove() {}, getContext() { return null; } });
  const __els = {};
  const __store = {};
  const localStorage = { getItem: k => (k in __store ? __store[k] : null), setItem: (k, v) => { __store[k] = String(v); }, removeItem: k => { delete __store[k]; } };
  const document = { getElementById: id => (__els[id] = __els[id] || __el()), querySelector: () => null, querySelectorAll: () => [], addEventListener() {},
    createElement: __el, body: __el(), documentElement: __el(), hidden: false, activeElement: null, fonts: { ready: Promise.resolve() } };
  const navigator = { userAgent: 'arena-server', onLine: true, serviceWorker: undefined, share: undefined, clipboard: undefined };
  const location = { hash: '', protocol: 'https:', href: 'https://arena.invalid/', search: '' };
  const matchMedia = () => ({ matches: false, addEventListener() {}, addListener() {} });
  const addEventListener = () => {}, removeEventListener = () => {}, scrollTo = () => {}, scrollY = 0;
  const setTimeout = () => 0, clearTimeout = () => {}, setInterval = () => 0, clearInterval = () => {}, requestAnimationFrame = () => 0;
  const window = { document, localStorage, navigator, location, matchMedia, addEventListener, removeEventListener, scrollTo, scrollY, innerWidth: 400, innerHeight: 800 };
  const self = window, top = window;
${code}
  ;ARENA_SANDBOX = true;
  return {
    getS: () => S, setS: v => { S = v; },
    setRandom: f => { const p = __rand; __rand = f; return p; },
    setSandbox: () => { ARENA_SANDBOX = true; },
    ${EXPORTS.join(', ')}
  };
};
`;
}

function writeEngine(root) {
  const html = fs.readFileSync(path.join(root, 'japa-or-stay.html'), 'utf8');
  const out = path.join(root, 'arena', 'server', 'engine.generated.js');
  fs.writeFileSync(out, generateEngine(html));
  return out;
}

module.exports = { generateEngine, writeEngine, gameScript };
if (require.main === module) console.log('Wrote', writeEngine(path.join(__dirname, '..')));
