// Embeds the portrait photos in art/portraits/*.webp into japa-or-stay.html as data URLs,
// so the game stays a single file that works offline (and as a claude.ai artifact).
// Run after adding or replacing a portrait:  node tools/embed-portraits.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'art', 'portraits');
const file = path.join(root, 'japa-or-stay.html');
const BEGIN = '/* PHOTOS:BEGIN (generated by tools/embed-portraits.js, do not edit by hand) */';
const END = '/* PHOTOS:END */';

const photos = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.webp')).sort()) {
  photos[path.basename(f, '.webp')] = 'data:image/webp;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64');
}
const block = `${BEGIN}\nconst PHOTOS = {\n${Object.entries(photos).map(([k, v]) => `  ${JSON.stringify(k)}: '${v}'`).join(',\n')}\n};\n${END}`;

let html = fs.readFileSync(file, 'utf8');
const a = html.indexOf(BEGIN), b = html.indexOf(END);
if (a < 0 || b < 0) throw new Error('PHOTOS markers not found in japa-or-stay.html');
html = html.slice(0, a) + block + html.slice(b + END.length);
fs.writeFileSync(file, html);
const kb = Math.round(Object.values(photos).reduce((n, v) => n + v.length, 0) / 1024);
console.log(`Embedded ${Object.keys(photos).length} portraits (${kb} KB) into japa-or-stay.html`);
